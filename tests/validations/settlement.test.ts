/**
 * Unit tests for the settlement payload and intent schemas (#644).
 *
 * These pin the validation contract itself: what a settlement request may
 * contain, what a participant share must look like, and what the API insists on
 * before it will turn an intent into a Stellar payment. The route-level proof
 * that these schemas are wired into the pipeline lives in
 * tests/settlement-payload-validation.test.ts.
 */
import { describe, it, expect } from "vitest";
import { Keypair } from "@stellar/stellar-sdk";
import {
  MAX_SIGNED_XDR_CHARS,
  freeformSettlementPayloadSchema,
  settleExpensePayloadSchema,
  settlementConfirmPayloadSchema,
  settlementExecutePayloadSchema,
  settlementIntentSchema,
  settlementPublicKeySchema,
  settlementShareSchema,
  signedXdrSchema,
} from "../../src/validations/settlement";
import { INTENT_VALIDITY_SECONDS } from "../../src/lib/time-bounds";

const FROM = Keypair.random();
const TO = Keypair.random();
const FROM_PUBLIC_KEY = FROM.publicKey();
const TO_PUBLIC_KEY = TO.publicKey();

/** The USDC issuer configured for the test environment (vitest.config.ts). */
const USDC_ISSUER = "GA5ZSEJYB37JRC5AVCIA5MOP4RHTM335X2KGX3IHOJAPP5RE34K4KZVN";

/** The message of the first issue at `path`, if any. */
function issueAt(
  result:
    | { success: true }
    | { success: false; error: { issues: { path: (string | number)[]; message: string }[] } },
  path: string[]
): string | undefined {
  if (result.success) return undefined;
  return result.error.issues.find(
    (issue) => issue.path.join(".") === path.join(".")
  )?.message;
}

describe("settlementPublicKeySchema", () => {
  it("accepts an ed25519 public key generated by the SDK", () => {
    expect(settlementPublicKeySchema.safeParse(FROM_PUBLIC_KEY).success).toBe(true);
  });

  it("rejects a secret seed", () => {
    const result = settlementPublicKeySchema.safeParse(FROM.secret());
    expect(result.success).toBe(false);
    if (!result.success) expect(result.error.issues[0].message).toMatch(/public key/i);
  });

  it("rejects a key-shaped string with a broken checksum", () => {
    const notAKey = `G${"A".repeat(55)}`;
    expect(settlementPublicKeySchema.safeParse(notAKey).success).toBe(false);
  });

  it("rejects an empty value, a truncated key, and a non-key string", () => {
    for (const value of ["", "GABC", "not-a-public-key", `${FROM_PUBLIC_KEY}x`]) {
      expect(settlementPublicKeySchema.safeParse(value).success).toBe(false);
    }
  });
});

describe("settleExpensePayloadSchema", () => {
  it("accepts an empty body (settle in the expense's own asset)", () => {
    expect(settleExpensePayloadSchema.safeParse({}).success).toBe(true);
  });

  it("accepts an XLM override and a USDC override with the configured issuer", () => {
    expect(
      settleExpensePayloadSchema.safeParse({ assetCode: "XLM", assetIssuer: null }).success
    ).toBe(true);
    expect(
      settleExpensePayloadSchema.safeParse({
        assetCode: "USDC",
        assetIssuer: USDC_ISSUER,
        validitySeconds: 120,
      }).success
    ).toBe(true);
  });

  it("rejects an unsupported asset code", () => {
    const result = settleExpensePayloadSchema.safeParse({ assetCode: "DOGE" });
    expect(issueAt(result, ["assetCode"])).toMatch(/Unsupported asset code/);
  });

  it("rejects an issuer supplied for the native asset", () => {
    const result = settleExpensePayloadSchema.safeParse({
      assetCode: "XLM",
      assetIssuer: USDC_ISSUER,
    });
    expect(issueAt(result, ["assetIssuer"])).toMatch(/native asset/);
  });

  it("rejects an issuer without an asset code instead of silently ignoring it", () => {
    const result = settleExpensePayloadSchema.safeParse({ assetIssuer: USDC_ISSUER });
    expect(issueAt(result, ["assetIssuer"])).toMatch(/together with assetCode/);
  });

  it("rejects an issuer that is not a valid public key", () => {
    const result = settleExpensePayloadSchema.safeParse({
      assetCode: "USDC",
      assetIssuer: "not-a-key",
    });
    expect(issueAt(result, ["assetIssuer"])).toMatch(/not a valid Stellar public key/);
  });

  it("bounds the signing window", () => {
    expect(settleExpensePayloadSchema.safeParse({ validitySeconds: 30 }).success).toBe(true);
    expect(settleExpensePayloadSchema.safeParse({ validitySeconds: 300 }).success).toBe(true);
    expect(settleExpensePayloadSchema.safeParse({ validitySeconds: 0 }).success).toBe(false);
    expect(settleExpensePayloadSchema.safeParse({ validitySeconds: 301 }).success).toBe(false);
  });

  it("rejects unknown keys", () => {
    const result = settleExpensePayloadSchema.safeParse({ amount: "10" });
    expect(result.success).toBe(false);
  });
});

describe("freeformSettlementPayloadSchema", () => {
  const valid = {
    toUserId: "user_2",
    amount: "10.5",
    assetCode: "XLM",
    assetIssuer: null,
  };

  it("accepts a valid settle-up payload", () => {
    const result = freeformSettlementPayloadSchema.safeParse(valid);
    expect(result.success).toBe(true);
    if (result.success) expect(result.data.amount).toBe("10.5");
  });

  it("requires the recipient", () => {
    expect(issueAt(freeformSettlementPayloadSchema.safeParse({ ...valid, toUserId: undefined }), ["toUserId"]))
      .toBeTruthy();
    expect(freeformSettlementPayloadSchema.safeParse({ ...valid, toUserId: "" }).success).toBe(false);
  });

  it("bounds and character-restricts the recipient id", () => {
    for (const toUserId of ["user 2", "user/2", "user.2", "u".repeat(65)]) {
      expect(freeformSettlementPayloadSchema.safeParse({ ...valid, toUserId }).success).toBe(false);
    }
  });

  it("rejects amounts that cannot be represented on-chain", () => {
    for (const amount of ["0", "0.0000000", "-5", "1.12345678", "1e5", " 10", "10 ", "abc", ""]) {
      expect(freeformSettlementPayloadSchema.safeParse({ ...valid, amount }).success).toBe(false);
    }
  });

  it("accepts the smallest representable positive amount", () => {
    expect(
      freeformSettlementPayloadSchema.safeParse({ ...valid, amount: "0.0000001" }).success
    ).toBe(true);
  });

  it("requires a supported asset", () => {
    expect(
      issueAt(freeformSettlementPayloadSchema.safeParse({ ...valid, assetCode: "DOGE" }), [
        "assetCode",
      ])
    ).toMatch(/Unsupported asset code/);
    expect(
      issueAt(
        freeformSettlementPayloadSchema.safeParse({ ...valid, assetCode: "USDC", assetIssuer: undefined }),
        []
      )
    ).toBeUndefined();
  });

  it("rejects a mismatched USDC issuer", () => {
    const result = freeformSettlementPayloadSchema.safeParse({
      ...valid,
      assetCode: "USDC",
      assetIssuer: Keypair.random().publicKey(),
    });
    expect(issueAt(result, ["assetIssuer"])).toMatch(/issuer mismatch/);
  });

  it("rejects unknown keys (a client-supplied expiry is not silently stripped)", () => {
    const result = freeformSettlementPayloadSchema.safeParse({
      ...valid,
      expiresAt: new Date(Date.now() + 60_000).toISOString(),
    });
    expect(result.success).toBe(false);
  });
});

describe("signedXdrSchema", () => {
  it("accepts an envelope and trims surrounding whitespace", () => {
    const result = signedXdrSchema.safeParse("  AAAA-signed-envelope  ");
    expect(result.success).toBe(true);
    if (result.success) expect(result.data).toBe("AAAA-signed-envelope");
  });

  it("rejects an empty or whitespace-only value", () => {
    expect(signedXdrSchema.safeParse("").success).toBe(false);
    expect(signedXdrSchema.safeParse("    ").success).toBe(false);
  });

  it("rejects an envelope with internal whitespace", () => {
    expect(signedXdrSchema.safeParse("AAAA\nBBBB").success).toBe(false);
    expect(signedXdrSchema.safeParse("AAAA BBBB").success).toBe(false);
  });

  it("rejects an envelope larger than the bound", () => {
    const oversized = "A".repeat(MAX_SIGNED_XDR_CHARS + 1);
    const result = signedXdrSchema.safeParse(oversized);
    expect(result.success).toBe(false);
    if (!result.success) expect(result.error.issues[0].message).toMatch(/too large/);
  });
});

describe("settlementConfirmPayloadSchema / settlementExecutePayloadSchema", () => {
  it("accepts a confirm body and rejects unknown keys", () => {
    expect(settlementConfirmPayloadSchema.safeParse({ signedXdr: "AAAA" }).success).toBe(true);
    expect(
      settlementConfirmPayloadSchema.safeParse({ signedXdr: "AAAA", settlementId: "settle_1" }).success
    ).toBe(false);
  });

  it("requires signedXdr on confirm", () => {
    expect(settlementConfirmPayloadSchema.safeParse({}).success).toBe(false);
    expect(settlementConfirmPayloadSchema.safeParse({ signedXdr: 123 }).success).toBe(false);
  });

  it("accepts an execute body addressed by id or short code", () => {
    expect(
      settlementExecutePayloadSchema.safeParse({
        settlementId: "settlement_1",
        signedXdr: "AAAA",
      }).success
    ).toBe(true);
    expect(
      settlementExecutePayloadSchema.safeParse({
        settlementId: "ABCD2345XY",
        signedXdr: "AAAA",
      }).success
    ).toBe(true);
  });

  it("rejects a malformed settlement id and missing envelope on execute", () => {
    expect(
      settlementExecutePayloadSchema.safeParse({
        settlementId: "not a valid id",
        signedXdr: "AAAA",
      }).success
    ).toBe(false);
    expect(
      settlementExecutePayloadSchema.safeParse({ settlementId: "settle_1" }).success
    ).toBe(false);
    expect(
      settlementExecutePayloadSchema.safeParse({
        settlementId: "settle_1",
        signedXdr: "  ",
      }).success
    ).toBe(false);
  });
});

describe("settlementShareSchema", () => {
  it("accepts a participant share", () => {
    const result = settlementShareSchema.safeParse({ userId: "user_1", amount: "3.3333334" });
    expect(result.success).toBe(true);
  });

  it("rejects an unrepresentable share amount", () => {
    for (const amount of ["0", "-1", "1.12345678", "NaN"]) {
      expect(settlementShareSchema.safeParse({ userId: "user_1", amount }).success).toBe(false);
    }
  });

  it("rejects a malformed participant id and unknown keys", () => {
    expect(
      settlementShareSchema.safeParse({ userId: "user 1", amount: "10" }).success
    ).toBe(false);
    expect(
      settlementShareSchema.safeParse({ userId: "user_1", amount: "10", role: "admin" }).success
    ).toBe(false);
  });
});

describe("settlementIntentSchema", () => {
  const validIntent = {
    fromPublicKey: FROM_PUBLIC_KEY,
    toPublicKey: TO_PUBLIC_KEY,
    assetCode: "XLM",
    assetIssuer: null,
    amount: "10",
    memoCode: "ABC2345XYZ",
    validitySeconds: 120,
  };

  it("accepts a well-formed intent and preserves it", () => {
    const result = settlementIntentSchema.safeParse(validIntent);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.fromPublicKey).toBe(FROM_PUBLIC_KEY);
      expect(result.data.toPublicKey).toBe(TO_PUBLIC_KEY);
      expect(result.data.amount).toBe("10");
      expect(result.data.validitySeconds).toBe(120);
    }
  });

  it("defaults the validity window to the shared intent window", () => {
    const { validitySeconds: _omitted, ...withoutWindow } = validIntent;
    const result = settlementIntentSchema.safeParse(withoutWindow);
    expect(result.success).toBe(true);
    if (result.success) expect(result.data.validitySeconds).toBe(INTENT_VALIDITY_SECONDS);
  });

  it("accepts a USDC intent with the configured issuer", () => {
    expect(
      settlementIntentSchema.safeParse({
        ...validIntent,
        assetCode: "USDC",
        assetIssuer: USDC_ISSUER,
      }).success
    ).toBe(true);
  });

  it("rejects a secret seed as the source or the destination", () => {
    expect(
      issueAt(settlementIntentSchema.safeParse({ ...validIntent, fromPublicKey: FROM.secret() }), [
        "fromPublicKey",
      ])
    ).toMatch(/Invalid Stellar account ID/);
    expect(
      settlementIntentSchema.safeParse({ ...validIntent, toPublicKey: TO.secret() }).success
    ).toBe(false);
  });

  it("rejects an unsupported asset or a native asset with an issuer", () => {
    expect(
      settlementIntentSchema.safeParse({ ...validIntent, assetCode: "DOGE" }).success
    ).toBe(false);
    expect(
      settlementIntentSchema.safeParse({
        ...validIntent,
        assetCode: "XLM",
        assetIssuer: USDC_ISSUER,
      }).success
    ).toBe(false);
  });

  it("rejects amounts outside Stellar's representable range", () => {
    for (const amount of ["0", "-1", "1.12345678", "922337203685.4775808", "1e3"]) {
      expect(settlementIntentSchema.safeParse({ ...validIntent, amount }).success).toBe(false);
    }
  });

  it("rejects a memo code that does not fit the settlement alphabet", () => {
    for (const memoCode of ["", "abc234", "ABC-234", "A".repeat(17)]) {
      expect(settlementIntentSchema.safeParse({ ...validIntent, memoCode }).success).toBe(false);
    }
  });

  it("bounds the validity window", () => {
    expect(settlementIntentSchema.safeParse({ ...validIntent, validitySeconds: 29 }).success).toBe(
      false
    );
    expect(settlementIntentSchema.safeParse({ ...validIntent, validitySeconds: 301 }).success).toBe(
      false
    );
  });

  it("rejects unknown keys", () => {
    expect(
      settlementIntentSchema.safeParse({ ...validIntent, sourceSequence: "123" }).success
    ).toBe(false);
  });
});
